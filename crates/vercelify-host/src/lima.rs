//! The macOS provider: Lima, with Apple's Virtualization framework (`vz`,
//! macOS 13+) or QEMU with Hypervisor.framework on older Macs. Both are
//! hardware-accelerated; there is no software-emulation fallback.
//!
//! Lima runs with its own `LIMA_HOME` inside Vercelify's data directory,
//! so the owner's own Lima/Colima instances are never seen or touched. The
//! guest mounts nothing from the Mac and forwards no ports to it: apps are
//! reached over the mesh (or a Cloudflare tunnel) from inside the guest.

use crate::provider::{
    image_sha512, image_url, GuestSpec, Observed, Provider, GUEST_NAME, MESH_CONTROL_PORT, MESH_WG_PORT,
};
use crate::{Error, Result};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::Duration;
use vercelify_core::host::{Virtualization, GIB, MIB};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VmType {
    Vz,
    Qemu,
}

pub struct Lima {
    pub limactl: PathBuf,
    /// `LIMA_HOME`: ours alone.
    pub home: PathBuf,
    pub vm_type: VmType,
}

/// macOS major version, e.g. 14.
pub fn macos_major(version: &str) -> Option<u32> {
    version.split('.').next()?.trim().parse().ok()
}

/// vz needs macOS 13; before that QEMU (with HVF) does the job.
pub fn vm_type_for(macos_version: &str) -> VmType {
    match macos_major(macos_version) {
        Some(m) if m >= 13 => VmType::Vz,
        _ => VmType::Qemu,
    }
}

/// Where `limactl` is: next to us (a bundled, pinned copy), then
/// `VERCELIFY_LIMACTL`, then the usual Homebrew places.
pub fn find_limactl() -> Option<PathBuf> {
    let mut c: Vec<PathBuf> = vec![];
    if let Some(p) = std::env::var_os("VERCELIFY_LIMACTL") {
        c.push(p.into());
    }
    if let Some(dir) = std::env::current_exe()
        .ok()
        .and_then(|e| e.parent().map(Path::to_path_buf))
    {
        c.push(dir.join("limactl"));
        c.push(dir.join("../lima/bin/limactl"));
    }
    c.push("/opt/homebrew/bin/limactl".into());
    c.push("/usr/local/bin/limactl".into());
    c.into_iter().find(|p| p.is_file())
}

fn gib(bytes: u64) -> String {
    let g = bytes as f64 / GIB as f64;
    if (g - g.round()).abs() < 1e-9 {
        format!("{}", g.round() as u64)
    } else {
        format!("{g:.3}")
    }
}

/// The instance's configuration (pure). No mounts, no port forwarding, no
/// containerd of Lima's own: the guest is a plain Debian server.
pub fn config(spec: &GuestSpec, vm_type: VmType) -> String {
    let arch = if spec.arch == "aarch64" { "aarch64" } else { "x86_64" };
    let vm = match vm_type {
        VmType::Vz => "vz",
        VmType::Qemu => "qemu",
    };
    format!(
        r#"# Vercelify environment (generated by vercelify-host; edits are replaced).
vmType: {vm}
os: Linux
arch: {arch}
images:
  - location: "{url}"
    arch: {arch}
    digest: "sha512:{digest}"
cpus: {cpus}
memory: "{mem}MiB"
disk: "{disk}GiB"
mounts: []
mountType: null
containerd:
  system: false
  user: false
# Nothing from the guest is forwarded to the Mac (no surprise ports on it),
# except a main server's two mesh ports.
portForwards:
{mesh}  - guestIP: "0.0.0.0"
    guestIPMustBeZero: false
    guestPortRange: [1, 65535]
    proto: any
    ignore: true
  - guestIP: "127.0.0.1"
    guestPortRange: [1, 65535]
    proto: any
    ignore: true
video:
  display: none
"#,
        mesh = if spec.expose_mesh {
            format!(
                "  - guestPort: {MESH_CONTROL_PORT}\n    hostIP: \"0.0.0.0\"\n    proto: tcp\n  - guestPort: {MESH_WG_PORT}\n    hostIP: \"0.0.0.0\"\n    proto: udp\n"
            )
        } else {
            String::new()
        },
        url = image_url(arch),
        digest = image_sha512(arch),
        cpus = spec.grant.cpus,
        mem = spec.grant.memory_bytes / MIB,
        disk = gib(spec.grant.disk_bytes),
    )
}

impl Lima {
    fn cmd(&self) -> Command {
        let mut c = Command::new(&self.limactl);
        c.env("LIMA_HOME", &self.home).stdin(Stdio::null());
        c
    }

    fn run(&self, args: &[&str]) -> Result<String> {
        let limit = match args.first().copied() {
            // The image download (~350 MB) on a slow link.
            Some("create") => Duration::from_secs(45 * 60),
            Some("start") => Duration::from_secs(15 * 60),
            Some("stop") | Some("delete") | Some("edit") => Duration::from_secs(5 * 60),
            _ => Duration::from_secs(60),
        };
        let child = self
            .cmd()
            .args(args)
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .map_err(|e| Error::Unavailable(format!("running limactl: {e}")))?;
        let out = crate::provider::wait_with_timeout(child, limit).map_err(|e| match e {
            crate::provider::Waited::TimedOut => Error::Unavailable(format!(
                "limactl {} took longer than {} minutes (a stalled download or a stuck VM?): retrying is safe",
                args.first().copied().unwrap_or(""),
                limit.as_secs() / 60
            )),
            crate::provider::Waited::Io(e) => Error::Unavailable(format!("running limactl: {e}")),
        })?;
        if out.status.success() {
            Ok(String::from_utf8_lossy(&out.stdout).into_owned())
        } else {
            Err(Error::Unavailable(format!(
                "limactl {}: {}",
                args.first().copied().unwrap_or(""),
                lima_error(&String::from_utf8_lossy(&out.stderr))
            )))
        }
    }

    fn yaml_path(&self) -> PathBuf {
        self.home.join(format!("{GUEST_NAME}.yaml"))
    }
}

/// What went wrong, from limactl's log: its error lines' messages, else
/// the last lines.
pub fn lima_error(stderr: &str) -> String {
    let errors: Vec<String> = stderr
        .lines()
        .filter(|l| l.contains("level=error") || l.contains("level=fatal"))
        .map(|l| {
            l.split_once("msg=")
                .map(|(_, m)| m.trim().trim_matches('"').replace("\\\"", "\""))
                .unwrap_or_else(|| l.to_string())
        })
        .collect();
    if errors.is_empty() {
        last_lines(stderr, 3)
    } else {
        errors.join(" / ")
    }
}

fn last_lines(s: &str, n: usize) -> String {
    let lines: Vec<&str> = s.lines().filter(|l| !l.trim().is_empty()).collect();
    lines[lines.len().saturating_sub(n)..].join(" / ")
}

/// `limactl list --json` prints one object per line.
pub fn parse_list(out: &str) -> Observed {
    for line in out.lines() {
        let Ok(v) = serde_json::from_str::<serde_json::Value>(line) else {
            continue;
        };
        if v["name"].as_str() != Some(GUEST_NAME) {
            continue;
        }
        return match v["status"].as_str() {
            Some("Running") => Observed::Running,
            Some("Stopped") => Observed::Stopped,
            // Broken: half-made; create() replaces it.
            _ => Observed::Stopped,
        };
    }
    Observed::Missing
}

impl Provider for Lima {
    fn name(&self) -> String {
        match self.vm_type {
            VmType::Vz => "lima-vz".into(),
            VmType::Qemu => "lima-qemu".into(),
        }
    }

    fn virtualization(&self) -> Virtualization {
        let hv = Command::new("sysctl")
            .args(["-n", "kern.hv_support"])
            .output()
            .ok()
            .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string());
        match hv.as_deref() {
            Some("1") => Virtualization::Ready,
            Some("0") => Virtualization::Unsupported {
                reason: "this Mac's processor can't run virtual machines".into(),
            },
            _ => Virtualization::Unknown,
        }
    }

    fn observe(&self) -> Result<Observed> {
        if !self.home.join(GUEST_NAME).exists() {
            return Ok(Observed::Missing);
        }
        Ok(parse_list(&self.run(&["list", "--json"])?))
    }

    fn create(&self, spec: &GuestSpec) -> Result<()> {
        std::fs::create_dir_all(&self.home).map_err(|e| Error::Internal(e.to_string()))?;
        if self.home.join(GUEST_NAME).exists() {
            // A half-made guest from an interrupted try: ours, replace it.
            let _ = self.run(&["delete", "--force", GUEST_NAME]);
        }
        crate::state::write_private(&self.yaml_path(), config(spec, self.vm_type).as_bytes())?;
        let y = self.yaml_path();
        self.run(&[
            "create",
            "--tty=false",
            &format!("--name={GUEST_NAME}"),
            &y.to_string_lossy(),
        ])?;
        Ok(())
    }

    fn start(&self) -> Result<()> {
        self.run(&["start", "--tty=false", GUEST_NAME]).map(|_| ())
    }

    fn stop(&self) -> Result<()> {
        if self.observe()? != Observed::Running {
            return Ok(());
        }
        self.run(&["stop", GUEST_NAME]).map(|_| ())
    }

    fn resize(&self, spec: &GuestSpec) -> Result<()> {
        let cpus = spec.grant.cpus.to_string();
        let mem = gib(spec.grant.memory_bytes);
        let disk = gib(spec.grant.disk_bytes);
        self.run(&[
            "edit",
            "--tty=false",
            "--cpus",
            &cpus,
            "--memory",
            &mem,
            "--disk",
            &disk,
            GUEST_NAME,
        ])
        .map(|_| ())
    }

    fn remove(&self) -> Result<()> {
        if self.home.join(GUEST_NAME).exists() {
            self.run(&["delete", "--force", GUEST_NAME])?;
        }
        Ok(())
    }

    fn exec(&self, script: &str) -> Result<String> {
        let mut child = self
            .cmd()
            .args(["shell", "--workdir", "/", GUEST_NAME, "sudo", "bash", "-s"])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .map_err(|e| Error::Unavailable(format!("running limactl shell: {e}")))?;
        child
            .stdin
            .take()
            .expect("piped")
            .write_all(script.as_bytes())
            .map_err(|e| Error::Unavailable(e.to_string()))?;
        // Provisioning installs Docker and Vercelify: generous, not endless.
        let out = crate::provider::wait_with_timeout(child, Duration::from_secs(40 * 60)).map_err(|e| match e {
            crate::provider::Waited::TimedOut => {
                Error::Unavailable("a step inside the environment took over 40 minutes: retrying is safe".into())
            }
            crate::provider::Waited::Io(e) => Error::Unavailable(e.to_string()),
        })?;
        if out.status.success() {
            Ok(String::from_utf8_lossy(&out.stdout).into_owned())
        } else {
            Err(Error::Unavailable(format!(
                "in the environment: {}",
                last_lines(&String::from_utf8_lossy(&out.stderr), 6)
            )))
        }
    }

    fn host_address(&self) -> &'static str {
        "host.lima.internal"
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use vercelify_core::host::EnvironmentGrant;

    #[test]
    fn config_is_closed_off_and_pinned() {
        let spec = GuestSpec {
            grant: EnvironmentGrant {
                memory_bytes: 4 * GIB + 512 * MIB,
                cpus: 3,
                disk_bytes: 40 * GIB,
                policy_version: 1,
            },
            arch: "aarch64".into(),
            expose_mesh: false,
        };
        let c = config(&spec, VmType::Vz);
        assert!(!c.contains("guestPort: "), "a worker opens nothing");
        let main = config(
            &GuestSpec {
                expose_mesh: true,
                ..spec.clone()
            },
            VmType::Vz,
        );
        let fwd = main.find("guestPort: 7443").expect("control port");
        assert!(main.contains("guestPort: 51820\n    hostIP: \"0.0.0.0\"\n    proto: udp"));
        assert!(
            fwd < main.find("ignore: true").unwrap(),
            "forwards come before the catch-all ignore"
        );
        assert!(c.contains("vmType: vz"));
        assert!(c.contains("memory: \"4608MiB\""));
        assert!(c.contains("cpus: 3"));
        assert!(c.contains("disk: \"40GiB\""));
        assert!(c.contains("mounts: []"), "no folders of the Mac");
        assert!(c.contains("ignore: true"), "no ports forwarded to the Mac");
        assert!(c.contains(&format!("sha512:{}", crate::provider::IMAGE_ARM64_SHA512)));
        assert!(c.contains("genericcloud-arm64-"));
        assert!(config(&spec, VmType::Qemu).contains("vmType: qemu"));
    }

    #[test]
    fn older_macs_use_qemu() {
        assert_eq!(vm_type_for("12.7.6"), VmType::Qemu);
        assert_eq!(vm_type_for("13.0"), VmType::Vz);
        assert_eq!(vm_type_for("27.0.1"), VmType::Vz);
        assert_eq!(vm_type_for("garbage"), VmType::Qemu);
    }

    #[test]
    fn errors_come_from_error_lines() {
        let log = "time=\"x\" level=info msg=\"Downloading the image\"\ntime=\"y\" level=fatal msg=\"failed to download: connection reset\"\n";
        assert_eq!(lima_error(log), "failed to download: connection reset");
        assert_eq!(lima_error("plain failure\n"), "plain failure");
    }

    #[test]
    fn list_output() {
        let out = "{\"name\":\"other\",\"status\":\"Running\"}\n{\"name\":\"vercelify\",\"status\":\"Stopped\"}\n";
        assert_eq!(parse_list(out), Observed::Stopped);
        assert_eq!(
            parse_list("{\"name\":\"vercelify\",\"status\":\"Running\"}"),
            Observed::Running
        );
        assert_eq!(
            parse_list("{\"name\":\"other\",\"status\":\"Running\"}"),
            Observed::Missing
        );
        assert_eq!(parse_list(""), Observed::Missing);
    }
}
