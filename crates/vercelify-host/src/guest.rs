//! What runs inside the guest: the provisioning script that turns a fresh
//! Debian image into a Vercelify server, and the checks that say it is
//! ready. Pure text generation, so it is reviewed and tested here.

use crate::Error;

/// The host manager's read-only status listener (guest → host), apart from
/// the management API so a guest can never reach the latter through it.
pub const STATUS_PORT: u16 = 7426;
/// The management API (owner token), on the host's loopback.
pub const API_PORT: u16 = 7425;

/// How the guest joins Vercelify.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Role {
    /// A worker of an existing main server, with its invite (`vfyj1.…`).
    Worker { join: String },
    /// The first server: the main one.
    Main,
}

#[derive(Debug, Clone)]
pub struct Provision {
    pub hostname: String,
    pub role: Role,
    /// The host as the guest sees it (`host.lima.internal`, `10.0.2.2`).
    pub host_address: String,
    /// `VERCELIFY_REF` for the installer: the release matching this host
    /// manager, so guest and manager move together.
    pub install_ref: String,
}

fn valid_hostname(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= 63
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '-')
        && !s.starts_with('-')
        && !s.ends_with('-')
}

fn valid_join(s: &str) -> bool {
    s.starts_with("vfyj1.") && s.len() < 4096 && s.chars().all(|c| c.is_ascii_alphanumeric() || "._-".contains(c))
}

fn valid_ref(s: &str) -> bool {
    !s.is_empty() && s.len() < 100 && s.chars().all(|c| c.is_ascii_alphanumeric() || "._/-".contains(c))
}

fn valid_host_address(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || ".-".contains(c))
}

impl Provision {
    /// The provisioning script (root, bash, idempotent: a retry re-runs it).
    /// Everything interpolated is validated first; nothing comes from the
    /// network into a shell unchecked.
    pub fn script(&self) -> Result<String, Error> {
        if !valid_hostname(&self.hostname) {
            return Err(Error::Invalid(format!(
                "`{}` is not a valid computer name",
                self.hostname
            )));
        }
        if !valid_ref(&self.install_ref) || !valid_host_address(&self.host_address) {
            return Err(Error::Invalid("invalid installer reference or host address".into()));
        }
        let role_flags = match &self.role {
            Role::Worker { join } => {
                if !valid_join(join) {
                    return Err(Error::Invalid("the invite should look like vfyj1.…".into()));
                }
                format!("--worker --join {join}")
            }
            Role::Main => String::new(),
        };
        let host = &self.host_address;
        let name = &self.hostname;
        let reference = &self.install_ref;
        Ok(format!(
            r#"#!/bin/bash
# Vercelify environment: provisioning (generated by vercelify-host).
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive

hostnamectl set-hostname {name}

# The clock must survive the computer sleeping: step it at once after a
# jump (mesh certificates and HTTPS renewals are time-bound).
apt-get update -qq
apt-get install -y -qq chrony curl ca-certificates iptables >/dev/null
sed -i 's/^makestep.*/makestep 1 -1/' /etc/chrony/chrony.conf
grep -q '^makestep' /etc/chrony/chrony.conf || echo 'makestep 1 -1' >> /etc/chrony/chrony.conf
systemctl restart chrony

# The agent reads the real computer's battery and temperature from the host
# manager instead of the virtual hardware's.
mkdir -p /etc/systemd/system/vercelify-agent.service.d
cat > /etc/systemd/system/vercelify-agent.service.d/host.conf <<'UNIT'
[Service]
Environment=VERCELIFY_HOST_STATUS=http://{host}:{status}/v1/host/status
UNIT

# Apps' containers must not reach the computer outside: the host's loopback
# (the owner's own services, the host manager) is behind this address.
cat > /usr/local/sbin/vercelify-guest-isolation <<'SH'
#!/bin/sh
set -e
ip=$(getent ahostsv4 {host} | awk 'NR==1{{print $1}}')
[ -n "$ip" ] || ip={host}
iptables -N VFY-HOST 2>/dev/null || iptables -F VFY-HOST
# The gateway is also the guest's DNS server (Lima): names must resolve.
iptables -A VFY-HOST -d "$ip" -p udp --dport 53 -j RETURN
iptables -A VFY-HOST -d "$ip" -p tcp --dport 53 -j RETURN
iptables -A VFY-HOST -d "$ip" -j DROP
iptables -C DOCKER-USER -j VFY-HOST 2>/dev/null || iptables -I DOCKER-USER -j VFY-HOST
SH
chmod 755 /usr/local/sbin/vercelify-guest-isolation
cat > /etc/systemd/system/vercelify-guest-isolation.service <<'UNIT'
[Unit]
Description=Keep app containers away from the host computer
After=docker.service
Requires=docker.service
PartOf=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/vercelify-guest-isolation

[Install]
WantedBy=docker.service
UNIT

if [ ! -x /usr/local/bin/vercelify-agent ]; then
  curl -fsSL --retry 5 -o /tmp/vercelify-install.sh \
    "https://raw.githubusercontent.com/shashank03-dev/vercelify-oss/{reference}/install.sh"
  VERCELIFY_REF={reference} bash /tmp/vercelify-install.sh \
    --hostname {name} {role_flags} --no-power-guard --no-display --no-desktop --no-remote
fi
systemctl daemon-reload
systemctl enable --now vercelify-guest-isolation.service
systemctl restart vercelify-agent
echo provisioned
"#,
            status = STATUS_PORT,
        ))
    }
}

/// Run in the guest to check it is ready: the agent answers, Docker runs,
/// the isolation rule is in place; prints the guest's clock last.
pub const HEALTH_SCRIPT: &str = r#"set -e
systemctl is-active --quiet docker
systemctl is-active --quiet vercelify-agent
curl -fsS -m 5 -o /dev/null http://127.0.0.1:7420/v1/health
iptables -C DOCKER-USER -j VFY-HOST
date +%s
"#;

/// Read [`HEALTH_SCRIPT`]'s output: ready, and the clock within 10 s of
/// the host's.
pub fn health_ok(output: &str, host_now: i64) -> Result<(), String> {
    let t: i64 = output
        .lines()
        .last()
        .and_then(|l| l.trim().parse().ok())
        .ok_or_else(|| "the environment didn't answer its health check".to_string())?;
    if (t - host_now).abs() > 10 {
        return Err(format!(
            "the environment's clock is {} s off: it is still syncing (or can't reach a time server)",
            t - host_now
        ));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn p(role: Role) -> Provision {
        Provision {
            hostname: "studio-mac".into(),
            role,
            host_address: "host.lima.internal".into(),
            install_ref: "v1.1.0".into(),
        }
    }

    #[test]
    fn worker_script_joins_and_isolates() {
        let s = p(Role::Worker {
            join: "vfyj1.abc_DEF-123".into(),
        })
        .script()
        .unwrap();
        assert!(s.contains("--worker --join vfyj1.abc_DEF-123"));
        assert!(s.contains("VERCELIFY_HOST_STATUS=http://host.lima.internal:7426/v1/host/status"));
        assert!(s.contains("iptables -I DOCKER-USER -j VFY-HOST"));
        let dns = s.find("--dport 53 -j RETURN").expect("DNS allowed");
        let drop = s.find("-d \"$ip\" -j DROP").expect("the rest dropped");
        assert!(dns < drop, "DNS is let through before the drop");
        assert!(s.contains("makestep 1 -1"));
        assert!(s.contains("VERCELIFY_REF=v1.1.0"));
        assert!(!s.contains(":7425"), "the guest is never told about the management API");
    }

    #[test]
    fn hostile_values_never_reach_the_shell() {
        assert!(p(Role::Worker {
            join: "vfyj1.x; rm -rf /".into()
        })
        .script()
        .is_err());
        let mut bad = p(Role::Main);
        bad.hostname = "a$(id)".into();
        assert!(bad.script().is_err());
        let mut bad = p(Role::Main);
        bad.install_ref = "main\"; curl evil".into();
        assert!(bad.script().is_err());
        let mut bad = p(Role::Main);
        bad.host_address = "x y".into();
        assert!(bad.script().is_err());
        assert!(!p(Role::Main).script().unwrap().contains("--worker"));
    }

    #[test]
    fn health_needs_a_close_clock() {
        assert!(health_ok("1000\n", 1005).is_ok());
        assert!(health_ok("1000\n", 1100).unwrap_err().contains("clock"));
        assert!(health_ok("", 1000).is_err());
    }
}
